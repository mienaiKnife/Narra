package com.mienaiknife.narra.ui.components

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.OutlinedTextFieldDefaults
import androidx.compose.material3.TextFieldColors
import androidx.compose.runtime.Composable
import androidx.compose.ui.unit.dp

/** The pill shape shared by every text field in the app. */
val NarraTextFieldShape = RoundedCornerShape(24.dp)

/** The border colors shared by every [androidx.compose.material3.OutlinedTextField]. */
@Composable
fun narraTextFieldColors(): TextFieldColors = OutlinedTextFieldDefaults.colors(
    unfocusedBorderColor = MaterialTheme.colorScheme.outlineVariant,
    focusedBorderColor = MaterialTheme.colorScheme.primary,
)
